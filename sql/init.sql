-- Complete rerunnable database initializer: drops and recreates every table, then seeds.
-- Standalone - paste it into a PostgreSQL SQL editor, run it with psql, or submit it to
-- SEMOSS as a multi-statement commit query (SEMOSS's SQL parser doesn't support explicit
-- BEGIN/COMMIT). RERUNNING WIPES ALL DATA.
--
-- After any schema change, run "Update schema" in the SEMOSS database editor (or the
-- refresh_database_ontology MCP tool). SEMOSS query metadata doesn't follow DDL on its own,
-- and stale metadata breaks joins even though the tables exist.
--
-- Conventions:
--   * snake_case table and column names (reactor aliases and JSON are camelCase).
--   * DATE for a calendar date; `timestamp -- UTC` for an instant (when something
--     happened). The database's .smss must set DATABASE_ZONEID to UTC. See "Dates" in
--     CLAUDE.md.
--   * Ids are VARCHAR(36) UUIDs generated by the app unless there's a natural key.

